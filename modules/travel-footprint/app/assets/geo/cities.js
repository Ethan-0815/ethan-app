  /** Resolve a free-text city name to coordinates, or null. */
  function lookup(name) {
    var key = (name === null || name === undefined) ? '' : String(name).trim();
    if (!key) return null;
    if (DB[key]) return DB[key];
    if (ALIASES[key] && DB[ALIASES[key]]) return DB[ALIASES[key]];

    // strip a trailing 市/县/区/镇 and retry
    var stripped = key.replace(/[市县区镇]$/, '');
    if (stripped && stripped !== key && DB[stripped]) return DB[stripped];
    if (stripped && ALIASES[stripped] && DB[ALIASES[stripped]]) return DB[ALIASES[stripped]];

    // case-insensitive for latin names
    var lower = key.toLowerCase();
    for (var k in DB) {
      if (!Object.prototype.hasOwnProperty.call(DB, k)) continue;
      if (k.toLowerCase() === lower) return DB[k];
    }
    for (var a in ALIASES) {
      if (!Object.prototype.hasOwnProperty.call(ALIASES, a)) continue;
      if (a.toLowerCase() === lower) return DB[ALIASES[a]] || null;
    }

    return null;
  }

  /** Suggestions for the city autocomplete field (offline prefix/substring match). */
  function suggest(query, limit) {
    var q = (query === null || query === undefined) ? '' : String(query).trim();
    var max = limit || 8;
    if (!q) return [];

    var lower = q.toLowerCase();
    var starts = [];
    var contains = [];
    var k;

    for (k in DB) {
      if (!Object.prototype.hasOwnProperty.call(DB, k)) continue;
      var kl = k.toLowerCase();
      if (kl.indexOf(lower) === 0) starts.push(DB[k]);
      else if (kl.indexOf(lower) !== -1) contains.push(DB[k]);
      if (starts.length >= max) break;
    }

    return starts.concat(contains).slice(0, max);
  }

